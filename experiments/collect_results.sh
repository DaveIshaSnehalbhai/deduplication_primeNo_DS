#!/usr/bin/env bash
# Converts experiments/results/*.csv into markdown tables and replaces the
# content between <!-- RESULTS:START --> and <!-- RESULTS:END --> markers
# in README.md.
#
# Usage: bash experiments/collect_results.sh

set -e
cd "$(dirname "$0")/.."  # repo root

RESULTS_DIR="experiments/results"
README="README.md"
TMP=$(mktemp)

csv_to_md_table() {
  local csv="$1"
  if [ ! -f "$csv" ]; then
    echo "_(no data — run the experiment first)_"
    return
  fi
  awk -F',' '
    NR==1 {
      printf "|"
      for (i=1;i<=NF;i++) printf " %s |", $i
      printf "\n|"
      for (i=1;i<=NF;i++) printf " --- |"
      printf "\n"
      next
    }
    {
      printf "|"
      for (i=1;i<=NF;i++) printf " %s |", $i
      printf "\n"
    }
  ' "$csv"
}

{
  echo "<!-- RESULTS:START -->"
  echo "<!-- Auto-generated by experiments/collect_results.sh — do not edit by hand -->"
  echo
  echo "### Experiment 1: Baseline Throughput (single client)"
  echo
  csv_to_md_table "$RESULTS_DIR/baseline_throughput.csv"
  echo
  echo "### Experiment 2: Concurrent Clients + Deduplication"
  echo
  csv_to_md_table "$RESULTS_DIR/concurrent_dedup.csv"
  echo
  echo "### Experiment 3: Replication Failover"
  echo
  csv_to_md_table "$RESULTS_DIR/replication_failover.csv"
  echo
  echo "### Experiment 4: Chandy-Lamport Snapshot (Client Failure)"
  echo
  csv_to_md_table "$RESULTS_DIR/snapshot_client_failure.csv"
  echo
  echo "<!-- RESULTS:END -->"
} > "$TMP"

if grep -q "RESULTS:START" "$README" 2>/dev/null; then
  python3 - "$README" "$TMP" << 'PYEOF'
import sys
readme_path, tmp_path = sys.argv[1], sys.argv[2]
with open(readme_path) as f:
    readme = f.read()
with open(tmp_path) as f:
    block = f.read()
start_marker = "<!-- RESULTS:START -->"
end_marker = "<!-- RESULTS:END -->"
start = readme.find(start_marker)
end = readme.find(end_marker) + len(end_marker)
new_readme = readme[:start] + block.strip() + readme[end:]
with open(readme_path, "w") as f:
    f.write(new_readme)
PYEOF
  echo "Updated $README in place."
else
  echo "No RESULTS:START marker found in $README — appending block at the end."
  cat "$TMP" >> "$README"
fi

rm -f "$TMP"
echo "Done."
